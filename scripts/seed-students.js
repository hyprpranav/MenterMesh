async function seed() {
  console.log(`Starting dataset seed for ${RAW_DATASET.length} students...`);
  let count = 0;
  for (const st of RAW_DATASET) {
    const uid = `student_${st.reg.toLowerCase()}`;
    await setDoc(doc(db, "users", uid), {
      uid,
      name: st.name,
      email: st.collegeEmail,
      collegeEmail: st.collegeEmail,
      personalEmail: st.personalEmail,
      registerNumber: st.reg,
      rollNumber: st.roll,
      phone: st.phone,
      dateOfBirth: st.dob,
      aadhaarNumber: st.aadhaar,
      address: st.address,
      bloodGroup: st.blood,
      department: st.dept,
      year: st.year,
      section: st.section,
      skills: st.skills,
      role: "student",
      status: "active",
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    }, { merge: true });
    count++;
    console.log(`[${count}/${RAW_DATASET.length}] Seeded student: ${st.name} (${st.reg})`);
  }
  console.log(`🎉 Successfully seeded ${count} students into Firestore!`);
  process.exit(0);
}

seed().catch((err) => {
  console.error("Seed error:", err);
  process.exit(1);
});
